export type DictKey = keyof typeof dictionary

export const LangContext = createContext<{ lang: Lang; setLang: (lang: Lang) => void }>({ lang: 'tr', setLang: () => undefined })

export function useT(): { t: (key: DictKey) => string; lang: Lang; setLang: (lang: Lang) => void } {
  const { lang, setLang } = useContext(LangContext)
  return { t: (key) => dictionary[key][lang], lang, setLang }
}
